const dictionaries: Record<Lang, Record<TranslationKey, string>> = { en, hi };

export type Translate = (key: TranslationKey) => string;

/** Non-reactive lookup, for use outside React (navigator options, etc.). */
export function translate(key: TranslationKey, lang?: Lang | null): string {
  const dict = dictionaries[lang ?? 'en'] ?? en;
  return dict[key] ?? en[key];
}

/**
 * Reactive translator. Subscribes to `lang` only, so switching language
 * re-renders text without pulling the rest of the store into the component.
 */
export function useT(): Translate {
  const lang = useDairyStore((s) => s.lang);
  return (key: TranslationKey) => translate(key, lang);
}

/** Current language, defaulting to English. */
export function useLang(): Lang {
  return useDairyStore((s) => s.lang) ?? 'en';
}
